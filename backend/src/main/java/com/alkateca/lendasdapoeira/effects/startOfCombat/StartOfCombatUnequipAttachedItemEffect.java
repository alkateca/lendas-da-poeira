package com.alkateca.lendasdapoeira.effects.startOfCombat;

import com.alkateca.lendasdapoeira.effects.Effect;
import com.alkateca.lendasdapoeira.effects.combat.OnEquipUnequipAttachedItemEffect;
import com.alkateca.lendasdapoeira.engine.GameEngine;
import com.alkateca.lendasdapoeira.entity.Card;
import com.alkateca.lendasdapoeira.enums.TurnPhase;

public class StartOfCombatUnequipAttachedItemEffect implements Effect {

    private final OnEquipUnequipAttachedItemEffect delegate = new OnEquipUnequipAttachedItemEffect();

    @Override
    public boolean predicate(Card sourceCard, TurnPhase turnPhase) {
        return turnPhase == TurnPhase.COMBAT_START;
    }

    @Override
    public void resolve(GameEngine gameEngine, Card sourceCard) {
        delegate.resolve(gameEngine, sourceCard);
    }
}
